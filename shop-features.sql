-- ========== 1) المنتجات ==========
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default 'ملابس',
  price numeric not null check (price >= 0),
  old_price numeric not null default 0,
  stock integer not null default 0 check (stock >= 0),
  image text default '',
  emoji text default '🛍️',
  description text default '',
  rating numeric not null default 0,
  reviews integer not null default 0,
  badge text default '',
  active boolean not null default true,
  sort integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.products enable row level security;
drop policy if exists "public read active" on public.products;
drop policy if exists "owner read all products" on public.products;
drop policy if exists "owner insert products" on public.products;
drop policy if exists "owner update products" on public.products;
drop policy if exists "owner delete products" on public.products;
create policy "public read active" on public.products for select to anon, authenticated using (active);
create policy "owner read all products" on public.products for select to authenticated using (public.is_owner());
create policy "owner insert products" on public.products for insert to authenticated with check (public.is_owner());
create policy "owner update products" on public.products for update to authenticated using (public.is_owner()) with check (public.is_owner());
create policy "owner delete products" on public.products for delete to authenticated using (public.is_owner());
grant select on public.products to anon;
grant select, insert, update, delete on public.products to authenticated;

-- ========== 2) الكوبونات (الأدمن بس يشوفها، والزبون بيتحقق منها عن طريق دالة) ==========
create table if not exists public.coupons (
  code text primary key,
  kind text not null check (kind in ('percent','fixed')),
  value numeric not null check (value > 0),
  min_total numeric not null default 0,
  expires_at timestamptz,
  max_uses integer,
  used_count integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.coupons enable row level security;
drop policy if exists "owner coupons all" on public.coupons;
create policy "owner coupons all" on public.coupons for all to authenticated using (public.is_owner()) with check (public.is_owner());
revoke all on public.coupons from anon;
grant select, insert, update, delete on public.coupons to authenticated;

-- ========== 3) أعمدة الطلب الجديدة ==========
alter table public.orders add column if not exists coupon_code text;
alter table public.orders add column if not exists discount numeric not null default 0;

-- ========== 4) حساب الخصم (جوّه السيرفر) ==========
create or replace function public.coupon_discount(p_code text, p_subtotal numeric) returns numeric
language plpgsql security definer set search_path = public as $$
declare c public.coupons; d numeric;
begin
  select * into c from public.coupons where code = upper(trim(p_code));
  if not found or not c.active then raise exception 'coupon_invalid:الكوبون غير صحيح'; end if;
  if c.expires_at is not null and c.expires_at < now() then raise exception 'coupon_invalid:الكوبون منتهي'; end if;
  if c.max_uses is not null and c.used_count >= c.max_uses then raise exception 'coupon_invalid:الكوبون خلص عدد مرات استخدامه'; end if;
  if p_subtotal < c.min_total then raise exception 'coupon_invalid:الحد الأدنى للطلب % جنيه', c.min_total; end if;
  d := case when c.kind = 'percent' then round(p_subtotal * least(c.value, 100) / 100) else least(c.value, p_subtotal) end;
  return d;
end $$;
revoke all on function public.coupon_discount(text, numeric) from public, anon, authenticated;

-- الزبون بيسأل: الكوبون ده صالح وبكام خصم؟ (من غير ما يشوف جدول الكوبونات)
create or replace function public.check_coupon(p_code text, p_subtotal numeric) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  return jsonb_build_object('ok', true, 'discount', public.coupon_discount(p_code, p_subtotal));
exception when others then
  return jsonb_build_object('ok', false, 'message', split_part(sqlerrm, ':', 2));
end $$;
revoke all on function public.check_coupon(text, numeric) from public;
grant execute on function public.check_coupon(text, numeric) to anon, authenticated;

-- ========== 5) تجهيز الطلب قبل الحفظ: الأسعار من الداتابيز، المخزون، الكوبون، الإجمالي ==========
create or replace function public.orders_prepare() returns trigger
language plpgsql security definer set search_path = public as $$
declare it jsonb; p public.products; q int; lines jsonb := '[]'::jsonb; sub numeric := 0; d numeric := 0;
begin
  if jsonb_typeof(new.items) <> 'array' or jsonb_array_length(new.items) = 0 then
    raise exception 'order_invalid:السلة فاضية';
  end if;
  for it in select * from jsonb_array_elements(new.items) loop
    q := (it->>'qty')::int;
    if q is null or q < 1 or q > 99 then raise exception 'order_invalid:الكمية غلط'; end if;
    select * into p from public.products where id = (it->>'id')::bigint and active;
    if not found then raise exception 'unavailable:%', coalesce(it->>'name', ''); end if;
    update public.products set stock = stock - q where id = p.id and stock >= q;
    if not found then raise exception 'out_of_stock:%', p.name; end if;
    lines := lines || jsonb_build_object('id', p.id, 'name', p.name, 'price', p.price, 'qty', q);
    sub := sub + p.price * q;
  end loop;
  if new.coupon_code is not null and trim(new.coupon_code) <> '' then
    new.coupon_code := upper(trim(new.coupon_code));
    d := public.coupon_discount(new.coupon_code, sub);
    update public.coupons set used_count = used_count + 1
      where code = new.coupon_code and (max_uses is null or used_count < max_uses);
    if not found then raise exception 'coupon_invalid:الكوبون خلص عدد مرات استخدامه'; end if;
  else
    new.coupon_code := null;
  end if;
  new.items := lines;
  new.discount := d;
  new.total := sub - d;
  return new;
end $$;
drop trigger if exists orders_prepare on public.orders;
create trigger orders_prepare before insert on public.orders for each row execute function public.orders_prepare();

-- لو الطلب اتلغى المخزون يرجع، ولو رجع تاني يتخصم
create or replace function public.orders_status_stock() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if old.status <> 'canceled' and new.status = 'canceled' then
    update public.products p set stock = p.stock + (x->>'qty')::int
      from jsonb_array_elements(new.items) x where p.id = (x->>'id')::bigint;
  elsif old.status = 'canceled' and new.status <> 'canceled' then
    update public.products p set stock = greatest(0, p.stock - (x->>'qty')::int)
      from jsonb_array_elements(new.items) x where p.id = (x->>'id')::bigint;
  end if;
  return new;
end $$;
drop trigger if exists orders_status_stock on public.orders;
create trigger orders_status_stock after update of status on public.orders for each row execute function public.orders_status_stock();

